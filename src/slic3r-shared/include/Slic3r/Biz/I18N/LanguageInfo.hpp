// ----------------------------------------------------------------------------
// psLanguageInfo: encapsulates psLanguage to OS native lang.desc.
//                 translation information
// ----------------------------------------------------------------------------

struct psLanguageInfo
{
    int Language;                       // wxLanguage id
    std::string LocaleTag;              // Tag of locale in BCP 47-like notation
    std::string CanonicalName;          // Canonical name, e.g. fr_FR
    std::string CanonicalRef;           // Canonical reference including region,
    //   if the name specifies the language only, e.g. fr_FR for fr;
    //   empty, if region is unknown or already part of the name.
#ifdef _WIN32
    /*wxUint32*/unsigned int WinLang,   // Win32 language identifiers
        WinSublang;
#endif // _WIN32
    std::string Description;            // human-readable name of the language in English
    std::string DescriptionNative;      // human-readable name of the language in native language
    psLayoutDirection LayoutDirection;
};

