inline bool is_shift(KeyCode code)
{
    return code == KeyCode::LShift || code == KeyCode::RShift;
}

inline bool is_ctrl(KeyCode code)
{
    return code == KeyCode::LCtrl || code == KeyCode::RCtrl;
}

inline bool is_alt(KeyCode code)
{
    return code == KeyCode::LAlt || code == KeyCode::RAlt;
}

inline bool is_meta(KeyCode code)
{
    return code == KeyCode::LMeta || code == KeyCode::RMeta;
}

// Returns a human-readable shortcut string (e.g. for menus, tooltips).
std::string to_string(KeyCode key_code);

// Returns a platform-specific shortcut string suitable for accelerator tables.
std::string to_accel_table_string(KeyCode key_code);

